/**
 * Refuse to deploy seeds that register the same document twice.
 *
 * This is the check that would have prevented the mess migration 0068
 * cleans up. Two seed files each inserted a source_document row for the
 * same fee schedule under the same payer, with different hardcoded UUIDs.
 * Nothing complained. The rules from each then cited a different id, so
 * one document appeared in the library as two, and per-document reporting
 * split down the middle.
 *
 * A database constraint cannot catch this. The real uniqueness key is
 * (url, payer_id, content_hash) — one row per VERSION of a document per
 * payer — because a second row at the same URL is exactly how the crawler
 * records that a watched document changed. The two offending seeds
 * invented DIFFERENT placeholder hashes, so they satisfied that constraint
 * while still describing one document twice.
 *
 * So the check belongs here, on the files, where the mistake is made:
 * no two seeds may claim the same (url, payer_id) under different ids.
 *
 *   node scripts/check-seed-documents.mjs
 *
 * Exit 0 = clean. Exit 1 = a collision, with the files named.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.argv[2] ?? '.';
const MANIFEST = path.join(ROOT, 'db/seed/MANIFEST');

if (!fs.existsSync(MANIFEST)) {
  console.error(`no manifest at ${MANIFEST}`);
  process.exit(2);
}

const seeds = fs.readFileSync(MANIFEST, 'utf8')
  .split(/\r?\n/)
  .map((l) => l.replace(/#.*/, '').trim())
  .filter(Boolean);

// Scan only each file's source_document INSERT block. The payer_rule
// inserts begin with the same ('<uuid>'::uuid, '<uuid>'::uuid, '<text>'
// shape — where that third field is the STATE, not a url — so scanning
// whole files reports hundreds of phantom collisions.
const byPair = new Map();   // "url\0payer" -> Map(id -> file)
let blocks = 0;
let rows = 0;

for (const seed of seeds) {
  const file = path.join(ROOT, 'db/seed', seed);
  if (!fs.existsSync(file)) {
    console.error(`FAIL  manifest lists a file that does not exist: ${seed}`);
    process.exit(1);
  }
  const sql = fs.readFileSync(file, 'utf8');
  const blockRe = /INSERT INTO source_document\b[\s\S]*?;/g;
  let block;
  while ((block = blockRe.exec(sql))) {
    blocks++;
    // Require an http(s) url in the third position — that is what
    // distinguishes a source_document row from anything else.
    const rowRe = /\(\s*'([0-9a-f-]{36})'::uuid,\s*'([0-9a-f-]{36})'::uuid,\s*'(https?:[^']+)'/g;
    let m;
    while ((m = rowRe.exec(block[0]))) {
      const [, id, payer, url] = m;
      rows++;
      const key = `${url}\u0000${payer}`;
      if (!byPair.has(key)) byPair.set(key, new Map());
      byPair.get(key).set(id, seed);
    }
  }
}

// ---- second check: no seed may REGISTER a synthetic document ---------
//
// ingestion-source-medicare-pdf.sql registered a Medicare final rule
// generated by scripts/gen-medicare-test-pdf.mjs and served from our own
// /test-fixtures/ as an ACTIVE ingestion source, bound to Traditional
// Medicare with document_type 'cms_pfs' — a 0.95 confidence band, and
// created_by 'crawler:cms_pfs', the same marker the real CY2026 Final
// Rule extraction writes. Invented rules that no one could tell from the
// genuine ones, in the library every practice bills against.
//
// Scoped to INSERT blocks on purpose. retire-cms-short-docs.sql names
// the same /test-fixtures/ path in a DELETE, to remove exactly this kind
// of row — flagging that would punish the cleanup for mentioning the mess.
const FIXTURE = /\/test-fixtures\/|localhost|127\.0\.0\.1|example\.(com|org)|\.invalid\b/i;
const fixtures = [];
for (const seed of seeds) {
  const sql = fs.readFileSync(path.join(ROOT, 'db/seed', seed), 'utf8');
  const blockRe = /INSERT INTO (ingestion_source|source_document)\b[\s\S]*?;/g;
  let block;
  while ((block = blockRe.exec(sql))) {
    for (const m of block[0].matchAll(/'((?:https?|upload):\/\/[^']+)'/g)) {
      if (FIXTURE.test(m[1])) fixtures.push({ seed, table: block[1], url: m[1] });
    }
  }
}

for (const f of fixtures) {
  console.error(`FIXTURE   ${f.seed} registers a non-production URL into ${f.table}`);
  console.error(`  ${f.url}`);
}
if (fixtures.length) {
  console.error('');
  console.error('A synthetic document must never become a production data source.');
  console.error('Remove the seed from db/seed/MANIFEST and run it by hand against a');
  console.error('test database instead.');
  process.exit(1);
}

const collisions = [...byPair.entries()].filter(([, ids]) => ids.size > 1);

for (const [key, ids] of collisions) {
  const [url, payer] = key.split('\u0000');
  console.error('COLLISION  one document registered under several ids');
  console.error(`  url    : ${url}`);
  console.error(`  payer  : ${payer}`);
  for (const [id, seed] of ids) console.error(`    ${id}  ${seed}`);
}

if (collisions.length) {
  console.error('');
  console.error(`${collisions.length} (url, payer_id) pair(s) claimed by more than one source_document id.`);
  console.error('Pick one id and use it in every seed that cites the document, so the');
  console.error('rules from all of them point at a single row.');
  process.exit(1);
}

console.log(`seed documents OK — ${rows} rows across ${blocks} INSERT block(s), ${byPair.size} distinct (url, payer_id) pairs, no collisions`);
