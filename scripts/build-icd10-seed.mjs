/**
 * Build db/seed/icd10cm-2027.sql from CMS's ICD-10-CM order file.
 *
 * The visit note's diagnosis picker searches the icd10 table, and until this
 * seed that table held 22 hand-picked codes (0007, 0009, 0010). Heart
 * failure, COPD, dementia, ESRD, ALS, pancreatic cancer, failure to thrive —
 * the diagnoses a palliative practice writes every day — were not in it, and
 * the picker takes only what the search returns, so a clinician could not
 * record them on a visit at all. Found on production on 2026-10-22: a
 * bereavement call could not record Z63.4 and had to carry the patient's
 * intake code instead.
 *
 * Source: CMS, "2027 Code Descriptions in Tabular Order" (FY2027 ICD-10-CM,
 * for encounters 2026-10-01 to 2027-09-30),
 * https://www.cms.gov/files/zip/2027-code-descriptions-tabular-order.zip,
 * file icd10cm_order_2027.txt. ICD-10-CM is a US government work in the
 * public domain.
 *
 *   node scripts/build-icd10-seed.mjs <path/to/icd10cm_order_2027.txt>
 *
 * Billable codes only. The order file also lists category headers (billable
 * flag 0), which are not valid on a claim and would only offer the clinician
 * a code the bill cannot carry. Descriptions are the long ones: the short
 * ones are abbreviated for claim forms ("Unsp dementia, unsp severity,
 * without beh/psych/mood/anx") and harder to search.
 *
 * Plain INSERT statements, not COPY: backend/test/integration/harness.ts
 * applies every MANIFEST seed through pool.query, which cannot stream COPY
 * data.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const RELEASE = {
  fiscalYear: 2027,
  effective: '2026-10-01',
  url: 'https://www.cms.gov/files/zip/2027-code-descriptions-tabular-order.zip',
  file: 'icd10cm_order_2027.txt',
};
const OUT = path.join(process.cwd(), 'db', 'seed', `icd10cm-${RELEASE.fiscalYear}.sql`);
const BATCH = 4000;

/**
 * ICD-10-CM chapters by first and last category, from the tabular list. FY2027
 * added categories QA0 and QA1 (genetic neurodevelopmental disorders,
 * inherited neoplasm predisposition), which the order file places after Q99
 * and before R00 — the end of chapter 17, which therefore runs to QA1. A
 * category outside every range stops the build rather than guessing.
 */
const CHAPTERS = [
  ['A00', 'B99'], ['C00', 'D49'], ['D50', 'D89'], ['E00', 'E89'], ['F01', 'F99'],
  ['G00', 'G99'], ['H00', 'H59'], ['H60', 'H95'], ['I00', 'I99'], ['J00', 'J99'],
  ['K00', 'K95'], ['L00', 'L99'], ['M00', 'M99'], ['N00', 'N99'], ['O00', 'O9A'],
  ['P00', 'P96'], ['Q00', 'QA1'], ['R00', 'R99'], ['S00', 'T88'], ['U00', 'U85'],
  ['V00', 'Y99'], ['Z00', 'Z99'],
];

/** A code as the order file writes it: no dot, 3 to 7 characters (QA0 has a letter second). */
const CODE = /^[A-Z][0-9A-Z][0-9A-Z][0-9A-Z]{0,4}$/;

function chapterOf(code) {
  const cat = code.slice(0, 3);
  for (const [first, last] of CHAPTERS) {
    if (cat >= first && cat <= last) return `${first}-${last}`;
  }
  throw new Error(`${code}: no ICD-10-CM chapter contains category ${cat}`);
}

const dotted = (code) => (code.length > 3 ? `${code.slice(0, 3)}.${code.slice(3)}` : code);
const sqlText = (s) => `'${s.replace(/'/g, "''")}'`;

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-icd10-seed.mjs <path/to/icd10cm_order_2027.txt>');
  process.exit(2);
}
const raw = fs.readFileSync(src);
const sha256 = crypto.createHash('sha256').update(raw).digest('hex');
const lines = raw.toString('latin1').split(/\r?\n/).filter((l) => l.trim() !== '');

// Fixed-width layout, per CMS's icd10OrderFiles.pdf: order number (5),
// code (7, left-aligned), billable flag (1), short description (60), long.
const byChapter = new Map();
let headers = 0;
const seen = new Set();
for (const line of lines) {
  const code = line.slice(6, 13).trim();
  const flag = line.slice(14, 15);
  const long = line.slice(77).trim();
  if (!CODE.test(code)) throw new Error(`unexpected code ${JSON.stringify(code)} in: ${line.slice(0, 40)}`);
  if (flag !== '0' && flag !== '1') throw new Error(`${code}: billable flag ${JSON.stringify(flag)}`);
  if (!long) throw new Error(`${code}: no long description`);
  if (/[^\x20-\x7e]/.test(long)) throw new Error(`${code}: description is not printable ASCII`);
  if (seen.has(code)) throw new Error(`${code}: listed twice`);
  seen.add(code);
  if (flag === '0') {
    headers++;
    continue;
  }
  const chapter = chapterOf(code);
  if (!byChapter.has(chapter)) byChapter.set(chapter, []);
  byChapter.get(chapter).push([dotted(code), long]);
}
const billable = [...byChapter.values()].reduce((n, rows) => n + rows.length, 0);

const out = [];
out.push(`-- ============================================================================
-- icd10cm-${RELEASE.fiscalYear}.sql — the full ICD-10-CM code set, FY${RELEASE.fiscalYear}.
-- GENERATED by scripts/build-icd10-seed.mjs. Do not edit by hand.
--
-- Source: CMS "${RELEASE.fiscalYear} Code Descriptions in Tabular Order", file ${RELEASE.file}
--   ${RELEASE.url}
--   sha256 of ${RELEASE.file}: ${sha256}
-- For encounters ${RELEASE.effective} onward. ICD-10-CM is public domain.
--
-- ${billable} billable codes (the file's ${headers} category headers are left
-- out: they are not valid on a claim), with CMS's long descriptions.
--
-- Until this seed the icd10 table held 22 hand-picked codes, and the visit
-- note's diagnosis picker accepts only what its search returns, so most
-- diagnoses a palliative practice records could not be put on a visit.
--
-- Earlier releases' rows, and the curated rows of 0007/0009/0010, are retired
-- (expiration_date ${RELEASE.effective}), so a search finds each code once,
-- as this release describes it. A re-run never revives a row a later release
-- has retired: ON CONFLICT leaves expiration_date alone.
-- ============================================================================

BEGIN;
`);

let batches = 0;
for (const [chapter, rows] of [...byChapter.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  for (let i = 0; i < rows.length; i += BATCH) {
    const chunk = rows.slice(i, i + BATCH);
    batches++;
    out.push(`INSERT INTO icd10 (code, description, billable, chapter, effective_date)
SELECT v.code, v.description, true, '${chapter}', DATE '${RELEASE.effective}'
  FROM (VALUES
${chunk.map(([c, d]) => `    (${sqlText(c)}, ${sqlText(d)})`).join(',\n')}
  ) AS v(code, description)
ON CONFLICT (code, effective_date) DO UPDATE
   SET description = EXCLUDED.description,
       billable    = EXCLUDED.billable,
       chapter     = EXCLUDED.chapter;
`);
  }
}

out.push(`-- Retire everything still live from before this release: the curated rows
-- (0007, 0009, 0010) and any earlier release. Codes this release kept are
-- live again above under ${RELEASE.effective}; codes it deleted stop being offered.
UPDATE icd10
   SET expiration_date = DATE '${RELEASE.effective}'
 WHERE expiration_date IS NULL
   AND effective_date < DATE '${RELEASE.effective}';

DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM icd10 WHERE effective_date = DATE '${RELEASE.effective}';
  IF n <> ${billable} THEN
    RAISE EXCEPTION 'icd10: % rows under FY${RELEASE.fiscalYear} (${RELEASE.effective}), expected ${billable}', n;
  END IF;
END $$;

COMMIT;
`);

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(
  `wrote ${path.relative(process.cwd(), OUT)}: ${billable} billable codes in ${byChapter.size} chapters, ` +
    `${batches} INSERT batches, ${headers} headers skipped, ${(fs.statSync(OUT).size / 1e6).toFixed(1)} MB`,
);
